/* Clients (valid code): compressed upload to /api/upload -> Vercel Blob URL.
   Trial: compressed image embeds into the page as a data URI. */
async function optimizeImage(file){
  if (file.size > 10*1024*1024) throw new Error('too-large');
  const url = URL.createObjectURL(file);
  try{
    const img = await new Promise((res,rej)=>{ const i=new Image(); i.onload=()=>res(i); i.onerror=rej; i.src=url; });
    const MAX = 1600;
    const scale = Math.min(1, MAX / Math.max(img.naturalWidth, img.naturalHeight));
    const w = Math.max(1, Math.round(img.naturalWidth*scale)), h = Math.max(1, Math.round(img.naturalHeight*scale));
    const c = document.createElement('canvas'); c.width=w; c.height=h;
    c.getContext('2d').drawImage(img, 0, 0, w, h);
    const keepPng = file.type==='image/png' && file.size < 400*1024 && scale===1;
    const type = keepPng ? 'image/png' : 'image/jpeg';
    const blob = await new Promise(res=>c.toBlob(res, type, .82));
    return { blob: blob || file, type: blob ? type : file.type };
  } finally { URL.revokeObjectURL(url); }
}
function blobToBase64(blob){
  return new Promise((res,rej)=>{
    const r = new FileReader();
    r.onload = ()=>res(String(r.result).split(',')[1]);
    r.onerror = rej;
    r.readAsDataURL(blob);
  });
}
async function handleImageUpload(file, path){
  const btn = $(`#rtab-block .up-btn[data-up="${path}"]`);
  const orig = btn ? btn.textContent : '';
  if (btn){ btn.disabled = true; btn.textContent = t('Uploading…'); }
  try{
    const { blob, type } = await optimizeImage(file);
    const b64 = await blobToBase64(blob);
    let finalUrl = null;
    if (clientMode){
      let code = null; try{ code = localStorage.getItem('lb-access'); }catch(e){}
      try{
        const r = await fetch('/api/upload', {
          method:'POST', headers:{'Content-Type':'application/json'},
          body: JSON.stringify({ code, name:file.name, type, data:b64 })
        });
        const d = await r.json();
        if (d.ok) finalUrl = d.url;
      }catch(e){ /* fall through to inline */ }
    }
    if (!finalUrl) finalUrl = `data:${type};base64,${b64}`;
    snapshot();
    const blk = state.blocks.find(x=>x.id===selectedId);
    if (blk) setByPath(blk, path, finalUrl);
    renderCanvas(); renderInspector(); autosave();
    toast(t('Image added'));
  }catch(e){
    toast(e && e.message==='too-large' ? t('That image is too large (max 10 MB)') : t('Upload failed. Try again, or paste a URL instead.'));
  }finally{
    if (btn){ btn.disabled = false; btn.textContent = orig; }
  }
}

