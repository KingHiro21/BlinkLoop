function currencySymbol(){ return CURRENCIES[state.meta.currency || 'PHP']; }
function swapCurrencySymbols(){
  const syms = Object.values(CURRENCIES).sort((a,b)=>b.length-a.length);
  const to = currencySymbol();
  state.blocks.filter(b=>b.type==='pricing').forEach(b=>{
    b.props.items.forEach(it=>{
      for (const s of syms){
        if (it.price && it.price.startsWith(s)){ it.price = to + it.price.slice(s.length); return; }
      }
    });
  });
}
